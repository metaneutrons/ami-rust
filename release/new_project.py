#!/usr/bin/env python3
"""Create an offline project with SDK path dependencies inside its root.

This helper copies only the verified installed SDK source subtree. It
does not copy host prerequisites, native payloads, or release archives. The
copy makes Cargo path-package identities independent of the installed SDK
prefix while retaining the same source bytes and nested SDK workspace.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import stat
import sys
import tempfile
import types

SDK_COPY_FILE_LIMIT = 1000
SDK_COPY_TOTAL_LIMIT = 8 * 1024 * 1024

SOURCE = '''#![no_std]
use amiga_os::{AppStatus, Context};

fn application(ctx: &Context) -> AppStatus {
    ctx.diagnostic(b"ami-rust hello", 1);
    AppStatus::Success
}

amiga_os::entry!(application);
'''

LOCK = '''# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
# Generated by ami-rust new_project.py; no registry dependencies.
version = 4

[[package]]
name = "amiga-os"
version = "0.1.0"
dependencies = [
 "aros-runtime",
 "aros-sdk",
]

[[package]]
name = "aros-alloc"
version = "0.1.0"
dependencies = [
 "aros-sys",
]

[[package]]
name = "aros-runtime"
version = "0.1.0"
dependencies = [
 "aros-alloc",
 "aros-sys",
]

[[package]]
name = "aros-sdk"
version = "0.1.0"
dependencies = [
 "aros-runtime",
 "aros-sys",
]

[[package]]
name = "aros-sys"
version = "0.1.0"

[[package]]
name = "hello-aros"
version = "0.1.0"
dependencies = [
 "amiga-os",
]
'''


def _installer_module():
    path = Path(__file__).with_name("install.py").resolve(strict=True)
    module = types.ModuleType("ami_rust_install")
    module.__file__ = str(path)
    exec(compile(path.read_bytes(), str(path), "exec"), module.__dict__)
    return module


def _write_new(path, data, mode):
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
    fd = os.open(str(path), flags, mode)
    try:
        os.fchmod(fd, mode)
        with os.fdopen(fd, "wb", closefd=False) as stream:
            stream.write(data)
            stream.flush()
            os.fsync(fd)
    finally:
        os.close(fd)


def _copy_sdk_sources(installer, prefix, receipt, stage):
    rows = [row for row in receipt["inventory"] if row["path"].startswith("sdk/")]
    if not rows or len(rows) > SDK_COPY_FILE_LIMIT:
        raise ValueError("installed SDK source exceeds the 1000-file project-copy limit")
    total = sum(row["bytes"] for row in rows)
    if total > SDK_COPY_TOTAL_LIMIT:
        raise ValueError("installed SDK source exceeds the 8 MiB project-copy limit")

    expected = {}
    for row in rows:
        path = row["path"]
        relative = path[len("sdk/"):]
        installer._portable_path(relative, "copied SDK source path")
        expected[relative] = (row["bytes"], row["sha256"])
    if len(expected) != len(rows):
        raise ValueError("installed SDK receipt contains duplicate source paths")

    destination = stage / "sdk-source"
    destination.mkdir(mode=0o755)
    for row in rows:
        source_relative = row["path"]
        relative = source_relative[len("sdk/"):]
        parts = installer._portable_path(relative, "copied SDK source path")
        source = prefix.joinpath(*installer._portable_path(source_relative,
                                                           "installed SDK source path"))
        info = source.lstat()
        if (not stat.S_ISREG(info.st_mode) or info.st_nlink != 1
                or info.st_size != row["bytes"]):
            raise ValueError(f"installed SDK source is not a private regular file: {relative}")
        data = installer._read_relative(prefix, source_relative,
                                        SDK_COPY_TOTAL_LIMIT,
                                        f"installed SDK source {relative}")
        digest = hashlib.sha256(data).hexdigest()
        if len(data) != row["bytes"] or digest != row["sha256"]:
            raise ValueError(f"installed SDK source differs from its receipt: {relative}")

        target = destination.joinpath(*parts)
        target.parent.mkdir(mode=0o755, parents=True, exist_ok=True)
        mode = 0o755 if info.st_mode & 0o111 else 0o644
        _write_new(target, data, mode)

    actual = {}
    for current, directories, files in os.walk(destination, topdown=True,
                                                  followlinks=False):
        current_path = Path(current)
        for name in directories:
            child = current_path / name
            if not stat.S_ISDIR(child.lstat().st_mode):
                raise ValueError("copied SDK source contains a symlink or special directory")
        for name in files:
            child = current_path / name
            info = child.lstat()
            if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                raise ValueError("copied SDK source contains a symlink or hard link")
            relative = child.relative_to(destination).as_posix()
            data = installer._read_fd(child, SDK_COPY_TOTAL_LIMIT,
                                       f"copied SDK source {relative}")
            actual[relative] = (len(data), hashlib.sha256(data).hexdigest())
    if actual != expected:
        raise ValueError("copied SDK source inventory does not match the installed SDK")
    return {"files": len(actual), "bytes": total}


def create(sdk, output, receipt_sha256):
    sdk = Path(os.path.abspath(os.fspath(sdk)))
    output = Path(os.path.abspath(os.fspath(output)))
    if sdk.resolve(strict=True) != sdk or sdk.name != "sdk":
        raise ValueError("select the canonical sdk/ directory of an installed release")
    if not (sdk / "contract/sdk.json").is_file():
        raise ValueError("selected installation has no SDK contract")
    if output.exists() or output.is_symlink() or not output.parent.is_dir():
        raise ValueError("project directory must be fresh")

    installer = _installer_module()
    installer._secure_user_directory(output.parent, "project parent")
    prefix, receipt, receipt_digest, selected = installer._installed(
        str(sdk.parent), receipt_sha256)
    if sdk != prefix / "sdk":
        raise ValueError("selected SDK is not the receipt-owned sdk/ directory")
    sdk_manifest = installer._read_relative(prefix, "sdk/contract/sdk.json",
                                            installer.MANIFEST_LIMIT,
                                            "installed SDK manifest")
    sdk_manifest_sha256 = hashlib.sha256(sdk_manifest).hexdigest()
    if sdk_manifest_sha256 != selected["sdk_manifest_sha256"]:
        raise ValueError("installed SDK manifest differs from the authenticated receipt")

    manifest = '''[workspace]
resolver = "3"
[workspace.package]
version = "0.1.0"
edition = "2024"
publish = false
license = "MIT OR Apache-2.0"
[package]
name = "hello-aros"
version = "0.1.0"
edition = "2024"
publish = false
license = "MIT OR Apache-2.0"
[lib]
crate-type = ["staticlib"]
[dependencies]
amiga-os = { path = "sdk-source/crates/public/amiga-os", default-features = false }
[profile.release]
opt-level = 2
panic = "abort"
lto = false
codegen-units = 1
incremental = false
debug = 0
strip = "none"
[profile.release.package.compiler_builtins]
codegen-units = 1
'''

    stage = Path(tempfile.mkdtemp(prefix=".ami-rust-project-",
                                  dir=str(output.parent)))
    try:
        (stage / "src").mkdir(mode=0o755)
        _write_new(stage / "Cargo.toml", manifest.encode(), 0o644)
        _write_new(stage / "Cargo.lock", LOCK.encode(), 0o644)
        _write_new(stage / "src/lib.rs", SOURCE.encode(), 0o644)
        binding = json.dumps({
            "schema": "ami-rust-project-sdk-binding-v1",
            "version": selected["version"],
            "sdk_manifest_sha256": sdk_manifest_sha256,
        }, sort_keys=True, indent=2) + "\n"
        _write_new(stage / "ami-rust-sdk.json", binding.encode(), 0o644)
        copied = _copy_sdk_sources(installer, prefix, receipt, stage)

        # Revalidate the complete installation before publishing the project.
        installer._installed(str(prefix), receipt_digest)
        installer._fsync_tree_dirs(stage)
        installer.rename_exclusive(stage, output)
    finally:
        if stage.exists():
            shutil.rmtree(stage)

    return {
        "project": str(output),
        "package": "hello-aros",
        "sdk_manifest_sha256": sdk_manifest_sha256,
        "sdk_source_copy": copied,
        "receipt_sha256": receipt_digest,
        "claim": "project-local SDK source bytes match the receipt-verified installed SDK; this does not establish publisher provenance or R1 qualification",
    }


if __name__ == "__main__":
    if not sys.flags.isolated or not sys.dont_write_bytecode:
        raise SystemExit("use the pinned Python with -I -B")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sdk", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--receipt-sha256", required=True)
    args = parser.parse_args()
    print(json.dumps(create(args.sdk, args.output, args.receipt_sha256), indent=2))
