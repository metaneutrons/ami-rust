use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::{
    collections::{BTreeMap, BTreeSet},
    env, fs,
    io::Write,
    path::{Path, PathBuf},
    process::{Command, Stdio},
};

const MANIFEST: &str = "bindings/aros-api.json";
/// ABI-v11 passes six integer arguments in registers (SysV) and the rest on the
/// stack; the generated adapter supports up to six stack arguments.
const REGISTER_ARGUMENTS: usize = 6;
const MAX_ARGUMENTS: usize = 12;
const GENERATED_NOTICE: &str = "// Generated by aros-api-gen. Do not edit by hand.\n";

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct ApiManifest {
    schema: String,
    functions: Vec<Function>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Function {
    crate_name: String,
    module: String,
    header: String,
    library: String,
    c_name: String,
    rust_name: String,
    vector: usize,
    #[serde(default)]
    minimum_version: usize,
    result: ResultType,
    arguments: Vec<Argument>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct ResultType {
    rust_type: String,
    kind: ResultKind,
}

#[derive(Clone, Copy, Debug, Deserialize)]
#[serde(rename_all = "snake_case")]
enum ResultKind {
    Void,
    Pointer,
    I8,
    I16,
    I32,
    U32,
    Isize,
    Usize,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Argument {
    name: String,
    rust_type: String,
}

#[derive(Serialize)]
struct Provenance {
    schema: &'static str,
    generator: &'static str,
    manifest_sha256: String,
    inputs: Vec<InputIdentity>,
}

#[derive(Serialize)]
struct InputIdentity {
    abi: &'static str,
    path: String,
    sha256: String,
}

struct Options {
    check: bool,
    repository: PathBuf,
    abi1_sdk: PathBuf,
    abi11_sdk: PathBuf,
}

fn main() {
    if let Err(error) = run() {
        eprintln!("aros-api-gen: {error}");
        std::process::exit(2);
    }
}

fn run() -> Result<(), String> {
    let options = parse_options()?;
    let manifest_path = options.repository.join(MANIFEST);
    let manifest_bytes = fs::read(&manifest_path).map_err(display_error)?;
    let manifest: ApiManifest = serde_json::from_slice(&manifest_bytes).map_err(display_error)?;
    validate_manifest(&manifest)?;

    let abi1_include = include_root(&options.abi1_sdk)?;
    let abi11_include = include_root(&options.abi11_sdk)?;
    let mut identities = Vec::new();
    validate_sdk("abi1", &abi1_include, &manifest, &mut identities)?;
    validate_sdk("abi11", &abi11_include, &manifest, &mut identities)?;

    let mut outputs = BTreeMap::new();
    outputs.insert(
        "crates/aros-sys/src/generated/mod.rs".to_owned(),
        format_rust(&generate_aros_sys_module(&manifest))?,
    );
    for abi in [Abi::V1, Abi::V11] {
        outputs.insert(
            format!("crates/aros-sys/src/generated/x86_64_{}.rs", abi.name()),
            format_rust(&generate_backend(&manifest, "aros-sys", abi)?)?,
        );
        outputs.insert(
            format!("crates/aros-mui-sys/src/x86_64_{}.rs", abi.name()),
            format_rust(&generate_backend(&manifest, "aros-mui-sys", abi)?)?,
        );
    }
    // Synthetic functions of 7 to 12 arguments exercise the stack-argument
    // adapter on each ABI against the native probes of the qualification
    // fixture; they are generated by the same code as the real bindings.
    let probes = probe_manifest();
    validate_manifest(&probes)?;
    for abi in [Abi::V1, Abi::V11] {
        outputs.insert(
            format!("tests/qualification/src/probe/x86_64_{}.rs", abi.name()),
            format_rust(&generate_backend(&probes, "probe", abi)?)?,
        );
    }
    let provenance = Provenance {
        schema: "ami-rust-aros-api-provenance-v1",
        generator: env!("CARGO_PKG_VERSION"),
        manifest_sha256: sha256(&manifest_bytes),
        inputs: identities,
    };
    let mut provenance_bytes = serde_json::to_vec_pretty(&provenance).map_err(display_error)?;
    provenance_bytes.push(b'\n');
    outputs.insert("bindings/provenance.json".to_owned(), provenance_bytes);

    for (relative, bytes) in outputs {
        let path = options.repository.join(&relative);
        if options.check {
            let actual = fs::read(&path)
                .map_err(|error| format!("cannot read generated file {relative}: {error}"))?;
            if actual != bytes {
                return Err(format!("generated file is stale: {relative}"));
            }
        } else {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent).map_err(display_error)?;
            }
            fs::write(&path, bytes).map_err(display_error)?;
        }
    }
    Ok(())
}

fn parse_options() -> Result<Options, String> {
    let mut arguments = env::args_os().skip(1);
    let command = arguments
        .next()
        .and_then(|value| value.into_string().ok())
        .ok_or_else(usage)?;
    let check = match command.as_str() {
        "generate" => false,
        "check" => true,
        _ => return Err(usage()),
    };
    let mut values = BTreeMap::new();
    while let Some(option) = arguments.next() {
        let option = option
            .into_string()
            .map_err(|_| "option names must be UTF-8".to_owned())?;
        if !["--repository", "--abi1-sdk", "--abi11-sdk"].contains(&option.as_str()) {
            return Err(format!("unknown option {option}; {}", usage()));
        }
        let value = arguments
            .next()
            .ok_or_else(|| format!("{option} requires a path"))?;
        if values
            .insert(option.clone(), PathBuf::from(value))
            .is_some()
        {
            return Err(format!("{option} may be supplied only once"));
        }
    }
    let mut take = |name: &str| {
        values
            .remove(name)
            .ok_or_else(|| format!("missing {name}; {}", usage()))
    };
    Ok(Options {
        check,
        repository: take("--repository")?,
        abi1_sdk: take("--abi1-sdk")?,
        abi11_sdk: take("--abi11-sdk")?,
    })
}

fn usage() -> String {
    "usage: aros-api-gen {generate|check} --repository PATH --abi1-sdk PATH --abi11-sdk PATH"
        .to_owned()
}

fn include_root(sdk: &Path) -> Result<PathBuf, String> {
    let direct = sdk.join("include");
    let root = if direct.is_dir() {
        direct
    } else {
        sdk.to_owned()
    };
    if !root.join("defines/exec.h").is_file() {
        return Err(format!(
            "SDK include root is incomplete: {}",
            root.display()
        ));
    }
    Ok(root)
}

fn validate_manifest(manifest: &ApiManifest) -> Result<(), String> {
    if manifest.schema != "ami-rust-aros-api-v1" {
        return Err("unsupported API manifest schema".to_owned());
    }
    let mut names = BTreeSet::new();
    for function in &manifest.functions {
        if function.arguments.len() > MAX_ARGUMENTS {
            return Err(format!(
                "{} has {} arguments, more than the supported x86-64 call surface of six register and {} stack arguments",
                function.c_name,
                function.arguments.len(),
                MAX_ARGUMENTS - REGISTER_ARGUMENTS
            ));
        }
        if !["aros-sys", "aros-mui-sys", "probe"].contains(&function.crate_name.as_str()) {
            return Err(format!("unsupported output crate: {}", function.crate_name));
        }
        let key = (&function.crate_name, &function.module, &function.rust_name);
        if !names.insert(key) {
            return Err(format!("duplicate Rust function: {}", function.rust_name));
        }
        validate_identifier(&function.module)?;
        validate_identifier(&function.rust_name)?;
        for argument in &function.arguments {
            validate_identifier(&argument.name)?;
        }
    }
    Ok(())
}

fn validate_identifier(value: &str) -> Result<(), String> {
    if value.is_empty()
        || !value
            .bytes()
            .all(|byte| byte == b'_' || byte.is_ascii_lowercase() || byte.is_ascii_digit())
        || value.as_bytes()[0].is_ascii_digit()
    {
        return Err(format!("invalid generated Rust identifier: {value}"));
    }
    Ok(())
}

fn validate_sdk(
    abi: &'static str,
    include: &Path,
    manifest: &ApiManifest,
    identities: &mut Vec<InputIdentity>,
) -> Result<(), String> {
    let headers: BTreeSet<_> = manifest
        .functions
        .iter()
        .map(|function| function.header.as_str())
        .collect();
    for header in headers {
        for family in ["clib", "defines"] {
            let relative = format!("{family}/{header}_protos.h");
            let relative = if family == "defines" {
                format!("defines/{header}.h")
            } else {
                relative
            };
            let bytes = fs::read(include.join(&relative)).map_err(display_error)?;
            identities.push(InputIdentity {
                abi,
                path: relative,
                sha256: sha256(&bytes),
            });
        }
    }
    for function in &manifest.functions {
        let clib_path = include.join(format!("clib/{}_protos.h", function.header));
        let defines_path = include.join(format!("defines/{}.h", function.header));
        let clib = fs::read_to_string(clib_path).map_err(display_error)?;
        let defines = fs::read_to_string(defines_path).map_err(display_error)?;
        let macro_name = format!("#define __{}_WB(", function.c_name);
        let Some(start) = defines.find(&macro_name) else {
            return Err(format!(
                "{abi} SDK lacks the expected {macro_name} macro in {}",
                function.header
            ));
        };
        let block = &defines[start..];
        let end = block.find("})").unwrap_or(block.len());
        let block = &block[..end];
        if clib.contains(&format!(", {},", function.c_name)) {
            verify_clib_block(&clib, function)?;
        } else {
            // Some libraries (devices) ship plain prototypes in `clib`; the
            // vector, library and argument count are then checked against the
            // `defines` macro and the plain prototype.
            verify_plain_block(&clib, block, function)?;
        }
        let requirement = block
            .split_once("AROS_LIBREQ(")
            .and_then(|(_, rest)| rest.split_once(')'))
            .and_then(|(arguments, _)| arguments.rsplit_once(','))
            .and_then(|(_, version)| version.trim().parse::<usize>().ok());
        if requirement != Some(function.minimum_version) {
            return Err(format!(
                "{abi} SDK minimum version differs for {}",
                function.c_name
            ));
        }
    }
    Ok(())
}

fn verify_plain_block(clib: &str, defines: &str, function: &Function) -> Result<(), String> {
    let marker = format!(" {}(", function.c_name);
    let start = clib
        .find(&marker)
        .ok_or_else(|| format!("missing AROS prototype for {}", function.c_name))?;
    let rest = &clib[start + marker.len()..];
    let end = rest
        .find(");")
        .ok_or_else(|| format!("unterminated AROS prototype for {}", function.c_name))?;
    let arguments = rest[..end].trim();
    let count = if arguments.is_empty() || arguments == "void" {
        0
    } else {
        arguments.matches(',').count() + 1
    };
    if count != function.arguments.len() {
        return Err(format!(
            "{} has {count} SDK arguments but {} manifest arguments",
            function.c_name,
            function.arguments.len()
        ));
    }
    let vector = format!(", {}, {})", function.vector, function.library);
    if !defines.contains(&vector) {
        return Err(format!(
            "{} does not have vector {} in {}",
            function.c_name, function.vector, function.library
        ));
    }
    Ok(())
}

fn verify_clib_block(header: &str, function: &Function) -> Result<(), String> {
    let marker = format!(", {},", function.c_name);
    let name = header
        .find(&marker)
        .ok_or_else(|| format!("missing AROS prototype for {}", function.c_name))?;
    let start = header[..name]
        .rfind("AROS_LP")
        .ok_or_else(|| format!("malformed AROS prototype for {}", function.c_name))?;
    let end = header[name..]
        .find("\n);")
        .map(|offset| name + offset + 3)
        .ok_or_else(|| format!("unterminated AROS prototype for {}", function.c_name))?;
    let block = &header[start..end];
    let count = block
        .strip_prefix("AROS_LP")
        .and_then(|rest| rest.split_once('('))
        .and_then(|(count, _)| count.parse::<usize>().ok())
        .ok_or_else(|| format!("invalid AROS argument count for {}", function.c_name))?;
    if count != function.arguments.len() {
        return Err(format!(
            "{} has {count} SDK arguments but {} manifest arguments",
            function.c_name,
            function.arguments.len()
        ));
    }
    let vector = format!(", {}, {}", function.vector, function.library);
    if !block.contains(&vector) {
        return Err(format!(
            "{} does not have vector {} in {}",
            function.c_name, function.vector, function.library
        ));
    }
    Ok(())
}

#[derive(Clone, Copy)]
enum Abi {
    V1,
    V11,
}

impl Abi {
    fn name(self) -> &'static str {
        match self {
            Self::V1 => "abi1",
            Self::V11 => "abi11",
        }
    }
}

/// Synthetic functions `probe_7` to `probe_12` with mixed argument widths.
fn probe_manifest() -> ApiManifest {
    const TYPES: [&str; 6] = ["u64", "u32", "*const c_void", "i32", "u16", "u8"];
    let functions = (REGISTER_ARGUMENTS + 1..=MAX_ARGUMENTS)
        .map(|count| Function {
            crate_name: "probe".to_owned(),
            module: "probe".to_owned(),
            header: "probe".to_owned(),
            library: "Probe".to_owned(),
            c_name: format!("Probe{count}"),
            rust_name: format!("probe_{count}"),
            vector: count,
            minimum_version: 0,
            result: ResultType {
                rust_type: "u64".to_owned(),
                kind: ResultKind::Usize,
            },
            arguments: (0..count)
                .map(|index| Argument {
                    name: format!("a{}", index + 1),
                    rust_type: TYPES[index % TYPES.len()].to_owned(),
                })
                .collect(),
        })
        .collect();
    ApiManifest {
        schema: "ami-rust-aros-api-v1".to_owned(),
        functions,
    }
}

fn generate_aros_sys_module(manifest: &ApiManifest) -> Vec<u8> {
    let modules: BTreeSet<_> = manifest
        .functions
        .iter()
        .filter(|function| function.crate_name == "aros-sys")
        .map(|function| function.module.as_str())
        .collect();
    let modules = modules.into_iter().collect::<Vec<_>>().join(", ");
    format!(
        "{GENERATED_NOTICE}\
         #[cfg(any(not(target_os = \"aros\"), target_abi = \"\", target_abi = \"abi1\"))]\n\
         #[path = \"x86_64_abi1.rs\"]\n\
         mod backend;\n\
         #[cfg(all(target_os = \"aros\", target_abi = \"abi11\"))]\n\
         #[path = \"x86_64_abi11.rs\"]\n\
         mod backend;\n\n\
         pub use backend::{{{modules}}};\n"
    )
    .into_bytes()
}

fn generate_backend(manifest: &ApiManifest, crate_name: &str, abi: Abi) -> Result<Vec<u8>, String> {
    let functions: Vec<_> = manifest
        .functions
        .iter()
        .filter(|function| function.crate_name == crate_name)
        .collect();
    let mut output = String::from(GENERATED_NOTICE);
    if crate_name == "probe" {
        output.push_str("use aros_sys::Library;\nuse core::ffi::c_void;\n");
    } else if crate_name == "aros-sys" {
        output.push_str("use crate::*;\n");
    } else {
        output.push_str(
            "use super::{IClass, Library, MuiCustomClass, Object, TagItem, c_char, c_void};\n",
        );
    }
    match abi {
        Abi::V1 => {
            if crate_name == "aros-sys" {
                output.push_str("use core::ffi::{c_char, c_void};\n");
            }
            output.push_str("use core::mem;\n\n");
        }
        Abi::V11 => {
            output.push_str("use core::arch::asm;\n");
            if crate_name == "aros-sys" {
                output.push_str("use core::ffi::{c_char, c_void};\n");
            }
            output.push('\n');
        }
    }
    output.push_str(
        "unsafe fn vector(base: *mut Library, offset: usize) -> *const c_void {\n\
         \x20   // SAFETY: x86-64 AROS library bases use a negative pointer-vector table.\n\
         \x20   unsafe { base.cast::<*const c_void>().sub(offset).read() }\n\
         }\n",
    );

    let mut modules = BTreeMap::<&str, Vec<&Function>>::new();
    for function in functions {
        modules.entry(&function.module).or_default().push(function);
    }
    for (module, functions) in modules {
        let nested = crate_name == "aros-sys";
        if nested {
            output.push_str(&format!("\npub mod {module} {{\n    use super::*;\n"));
        }
        for function in functions {
            output.push_str(&generate_function(function, abi, nested)?);
        }
        if nested {
            output.push_str("}\n");
        }
    }
    Ok(output.into_bytes())
}

fn generate_function(function: &Function, abi: Abi, nested: bool) -> Result<String, String> {
    let indent = if nested { "    " } else { "" };
    let mut output = format!(
        "\n{indent}/// Raw `{}` call through {} vector {} (minimum version {}).\n\
         {indent}///\n\
         {indent}/// # Safety\n\
         {indent}/// `base` and every pointer argument must satisfy the native AROS contract.\n\
         {indent}pub unsafe fn {}(\n{indent}    base: *mut Library,\n",
        function.c_name,
        function.library,
        function.vector,
        function.minimum_version,
        function.rust_name
    );
    for argument in &function.arguments {
        output.push_str(&format!(
            "{indent}    {}: {},\n",
            argument.name, argument.rust_type
        ));
    }
    output.push_str(&format!("{indent})"));
    if !matches!(function.result.kind, ResultKind::Void) {
        output.push_str(&format!(" -> {}", function.result.rust_type));
    }
    output.push_str(" {\n");
    match abi {
        Abi::V1 => generate_abi1_body(&mut output, function, indent),
        Abi::V11 => generate_abi11_body(&mut output, function, indent)?,
    }
    output.push_str(&format!("{indent}}}\n"));
    Ok(output)
}

fn generate_abi1_body(output: &mut String, function: &Function, indent: &str) {
    let result = if matches!(function.result.kind, ResultKind::Void) {
        String::new()
    } else {
        format!(" -> {}", function.result.rust_type)
    };
    let arguments = function
        .arguments
        .iter()
        .map(|argument| argument.name.as_str())
        .chain(std::iter::once("base"))
        .collect::<Vec<_>>()
        .join(", ");
    output.push_str(&format!(
        "{indent}    type Function = unsafe extern \"C\" fn(\n"
    ));
    for argument in &function.arguments {
        output.push_str(&format!("{indent}        {},\n", argument.rust_type));
    }
    output.push_str(&format!(
        "{indent}        *mut Library,\n{indent}    ){result};\n\
         {indent}    // SAFETY: the vector and base-last ABI are verified against both pinned SDKs.\n\
         {indent}    let function: Function = unsafe {{ mem::transmute(vector(base, {})) }};\n\
         {indent}    // SAFETY: the caller owns the raw native contract.\n\
         {indent}    unsafe {{ function({arguments}) }}\n",
        function.vector
    ));
}

fn generate_abi11_body(
    output: &mut String,
    function: &Function,
    indent: &str,
) -> Result<(), String> {
    const REGISTERS: [&str; REGISTER_ARGUMENTS] = ["rdi", "rsi", "rdx", "rcx", "r8", "r9"];
    output.push_str(&format!(
        "{indent}    let function = unsafe {{ vector(base, {}) }};\n",
        function.vector
    ));
    if !matches!(function.result.kind, ResultKind::Void) {
        output.push_str(&format!(
            "{indent}    let result: {};\n",
            asm_result_type(function.result.kind)
        ));
    }
    let stack_arguments = function.arguments.get(REGISTERS.len()..).unwrap_or(&[]);
    if !stack_arguments.is_empty() {
        // The stack arguments are copied from this array to the outgoing
        // argument area, one eight-byte slot each, in call order.
        output.push_str(&format!(
            "{indent}    let stack_arguments: [usize; {}] = [\n",
            stack_arguments.len()
        ));
        for argument in stack_arguments {
            output.push_str(&format!("{indent}        {} as usize,\n", argument.name));
        }
        output.push_str(&format!("{indent}    ];\n"));
    }
    // The outgoing area keeps the stack 16-byte aligned at the call.
    let frame = stack_arguments.len().div_ceil(2) * 16;
    let mut sequence = String::new();
    if !stack_arguments.is_empty() {
        sequence.push_str(&format!("{indent}            \"sub rsp, {frame}\",\n"));
        for slot in 0..stack_arguments.len() {
            sequence.push_str(&format!(
                "{indent}            \"mov r11, [{{stack}} + {}]\",\n\
                 {indent}            \"mov [rsp + {}], r11\",\n",
                slot * 8,
                slot * 8
            ));
        }
    }
    sequence.push_str(&format!("{indent}            \"call {{function}}\",\n"));
    if !stack_arguments.is_empty() {
        sequence.push_str(&format!("{indent}            \"add rsp, {frame}\",\n"));
    }
    output.push_str(&format!(
        "{indent}    // SAFETY: ABI-v11 uses the SysV argument registers and requires the library base in r12.\n\
         {indent}    unsafe {{\n\
         {indent}        asm!(\n\
         {sequence}\
         {indent}            function = in(reg) function,\n\
         {indent}            in(\"r12\") base,\n"
    ));
    for (argument, register) in function.arguments.iter().zip(REGISTERS) {
        output.push_str(&format!(
            "{indent}            in(\"{register}\") {} as usize,\n",
            argument.name
        ));
    }
    if !stack_arguments.is_empty() {
        output.push_str(&format!(
            "{indent}            stack = in(reg) stack_arguments.as_ptr(),\n\
             {indent}            out(\"r11\") _,\n"
        ));
    }
    if !matches!(function.result.kind, ResultKind::Void) {
        let register = match function.result.kind {
            ResultKind::I8 | ResultKind::I16 | ResultKind::I32 | ResultKind::U32 => "eax",
            ResultKind::Pointer | ResultKind::Isize | ResultKind::Usize => "rax",
            ResultKind::Void => return Err("void result reached output register".to_owned()),
        };
        output.push_str(&format!(
            "{indent}            lateout(\"{register}\") result,\n"
        ));
    }
    output.push_str(&format!(
        "{indent}            clobber_abi(\"C\"),\n\
         {indent}        );\n\
         {indent}    }}\n"
    ));
    if !matches!(function.result.kind, ResultKind::Void) {
        output.push_str(&format!(
            "{indent}    {}\n",
            convert_result(function.result.kind, &function.result.rust_type)
        ));
    }
    Ok(())
}

fn asm_result_type(kind: ResultKind) -> &'static str {
    match kind {
        ResultKind::I8 | ResultKind::I16 | ResultKind::I32 => "i32",
        ResultKind::U32 => "u32",
        ResultKind::Pointer | ResultKind::Isize | ResultKind::Usize => "usize",
        ResultKind::Void => "()",
    }
}

fn convert_result(kind: ResultKind, rust_type: &str) -> String {
    match kind {
        ResultKind::I8 | ResultKind::I16 => format!("result as {rust_type}"),
        ResultKind::Pointer | ResultKind::Isize | ResultKind::Usize => {
            format!("result as {rust_type}")
        }
        ResultKind::I32 | ResultKind::U32 => "result".to_owned(),
        ResultKind::Void => String::new(),
    }
}

fn sha256(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let digest = Sha256::digest(bytes);
    let mut encoded = String::with_capacity(digest.len() * 2);
    for byte in digest {
        encoded.push(char::from(HEX[usize::from(byte >> 4)]));
        encoded.push(char::from(HEX[usize::from(byte & 0x0f)]));
    }
    encoded
}

fn format_rust(source: &[u8]) -> Result<Vec<u8>, String> {
    let rustfmt = env::var_os("RUSTFMT").unwrap_or_else(|| "rustfmt".into());
    let mut child = Command::new(rustfmt)
        .args(["--emit", "stdout", "--edition", "2024"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|error| format!("cannot start rustfmt: {error}"))?;
    child
        .stdin
        .take()
        .ok_or_else(|| "rustfmt stdin is unavailable".to_owned())?
        .write_all(source)
        .map_err(display_error)?;
    let output = child.wait_with_output().map_err(display_error)?;
    if !output.status.success() {
        return Err(format!(
            "rustfmt rejected generated source: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        ));
    }
    Ok(output.stdout)
}

fn display_error(error: impl std::fmt::Display) -> String {
    error.to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn function(count: usize) -> Function {
        Function {
            crate_name: "aros-sys".to_owned(),
            module: "test".to_owned(),
            header: "test".to_owned(),
            library: "Test".to_owned(),
            c_name: "Test".to_owned(),
            rust_name: "test".to_owned(),
            vector: 9,
            minimum_version: 0,
            result: ResultType {
                rust_type: "u32".to_owned(),
                kind: ResultKind::U32,
            },
            arguments: (0..count)
                .map(|index| Argument {
                    name: format!("a{index}"),
                    rust_type: "u32".to_owned(),
                })
                .collect(),
        }
    }

    fn manifest(count: usize) -> ApiManifest {
        ApiManifest {
            schema: "ami-rust-aros-api-v1".to_owned(),
            functions: vec![function(count)],
        }
    }

    fn abi11(count: usize) -> String {
        let mut text = String::new();
        generate_abi11_body(&mut text, &function(count), "").unwrap();
        text
    }

    #[test]
    fn twelve_arguments_are_accepted_and_thirteen_are_refused() {
        assert!(validate_manifest(&manifest(12)).is_ok());
        let error = validate_manifest(&manifest(13)).unwrap_err();
        assert!(error.contains("13 arguments"), "{error}");
    }

    #[test]
    fn registers_only_calls_use_no_stack() {
        let text = abi11(6);
        assert!(!text.contains("rsp"), "{text}");
        assert!(text.contains("in(\"r9\") a5 as usize"));
    }

    #[test]
    fn stack_arguments_get_a_16_byte_aligned_frame() {
        for (count, frame, slots) in [(7, 16, 1), (8, 16, 2), (9, 32, 3), (12, 48, 6)] {
            let text = abi11(count);
            assert!(
                text.contains(&format!("\"sub rsp, {frame}\"")),
                "{count}: {text}"
            );
            assert!(
                text.contains(&format!("\"add rsp, {frame}\"")),
                "{count}: {text}"
            );
            assert!(
                text.contains(&format!("let stack_arguments: [usize; {slots}]")),
                "{count}: {text}"
            );
            for slot in 0..slots {
                assert!(
                    text.contains(&format!("\"mov [rsp + {}], r11\"", slot * 8)),
                    "{text}"
                );
                assert!(
                    text.contains(&format!("[{{stack}} + {}]", slot * 8)),
                    "{text}"
                );
            }
            assert!(!text.contains(&format!("[rsp + {}]", slots * 8)), "{text}");
            // The seventh argument is the first stack slot, in call order.
            assert!(text.contains("[usize; "));
            assert!(text.contains("a6 as usize,"));
        }
    }

    #[test]
    fn the_probe_manifest_covers_seven_to_twelve_arguments() {
        let probes = probe_manifest();
        let counts: Vec<_> = probes.functions.iter().map(|f| f.arguments.len()).collect();
        assert_eq!(counts, [7, 8, 9, 10, 11, 12]);
        assert!(validate_manifest(&probes).is_ok());
    }

    #[test]
    fn abi1_passes_the_base_last_whatever_the_argument_count() {
        let mut text = String::new();
        generate_abi1_body(&mut text, &function(12), "");
        assert!(text.contains("a11, base"), "{text}");
    }
}
